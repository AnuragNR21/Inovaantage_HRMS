const PAYROLL_STATES = Object.freeze({
  DRAFT: 'DRAFT',
  PROCESSING: 'PROCESSING',
  VALIDATED: 'VALIDATED',
  APPROVED: 'APPROVED',
  FINALIZED: 'FINALIZED',
  HOLD: 'HOLD',
  FAILED: 'FAILED'
});

const ALLOWED_TRANSITIONS = Object.freeze({
  [PAYROLL_STATES.DRAFT]: [PAYROLL_STATES.PROCESSING, PAYROLL_STATES.FAILED],
  [PAYROLL_STATES.PROCESSING]: [PAYROLL_STATES.VALIDATED, PAYROLL_STATES.FAILED],
  [PAYROLL_STATES.VALIDATED]: [PAYROLL_STATES.APPROVED, PAYROLL_STATES.FAILED],
  [PAYROLL_STATES.APPROVED]: [PAYROLL_STATES.FINALIZED],
  [PAYROLL_STATES.FINALIZED]: [PAYROLL_STATES.HOLD],
  [PAYROLL_STATES.HOLD]: [PAYROLL_STATES.FINALIZED],
  [PAYROLL_STATES.FAILED]: [PAYROLL_STATES.PROCESSING]
});

function canTransition(fromState, toState) {
  return (ALLOWED_TRANSITIONS[fromState] || []).includes(toState);
}

module.exports = { PAYROLL_STATES, ALLOWED_TRANSITIONS, canTransition };
