-- ------------------------------------------------------------
-- EMPLOYEES
-- ------------------------------------------------------------
CREATE TABLE employees (
    employee_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_code    VARCHAR2(20)  NOT NULL,
    full_name        VARCHAR2(150) NOT NULL,
    department       VARCHAR2(100),
    designation      VARCHAR2(100),
    email            VARCHAR2(150),
    phone            VARCHAR2(20),
    date_of_joining  DATE,
    bank_account     VARCHAR2(40),
    bank_name        VARCHAR2(100),
    ifsc_code        VARCHAR2(20),
    pan_no           VARCHAR2(10),
    status           VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at       TIMESTAMP DEFAULT SYSTIMESTAMP,
    updated_at       TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT uq_employee_code UNIQUE (employee_code),
    CONSTRAINT ck_employee_status CHECK (status IN ('ACTIVE','INACTIVE'))
);

CREATE INDEX idx_employees_name ON employees (full_name);
CREATE INDEX idx_employees_dept ON employees (department);

-- ------------------------------------------------------------
-- APP_USERS (portal login credentials)
-- ------------------------------------------------------------
CREATE TABLE app_users (
    user_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR2(60)  NOT NULL,
    password_hash  VARCHAR2(200) NOT NULL,
    full_name      VARCHAR2(150),
    role           VARCHAR2(20) DEFAULT 'ADMIN' NOT NULL,
    employee_id    NUMBER,
    email          VARCHAR2(150),
    is_active      NUMBER(1) DEFAULT 1 NOT NULL,
    failed_login_count NUMBER(5) DEFAULT 0 NOT NULL,
    last_failed_login_at TIMESTAMP,
    locked_until   TIMESTAMP,
    last_login_at  TIMESTAMP,
    password_changed_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    password_version NUMBER(10) DEFAULT 1 NOT NULL,
    must_change_password NUMBER(1) DEFAULT 1 NOT NULL,
    created_at     TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT uq_username UNIQUE (username),
    CONSTRAINT ck_user_role CHECK (role IN ('ADMIN','HR','VIEWER')),
    CONSTRAINT ck_user_active CHECK (is_active IN (0,1)),
    CONSTRAINT ck_user_password_change CHECK (must_change_password IN (0,1)),
    CONSTRAINT fk_user_employee FOREIGN KEY (employee_id) REFERENCES employees(employee_id)
);

CREATE TABLE user_sessions (
    token_hash          VARCHAR2(64) PRIMARY KEY,
    user_id             NUMBER NOT NULL,
    created_at          TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    last_seen_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    expires_at          TIMESTAMP NOT NULL,
    absolute_expires_at TIMESTAMP NOT NULL,
    ip_address          VARCHAR2(64),
    user_agent          VARCHAR2(500),
    password_version    NUMBER(10) NOT NULL,
    revoked_at          TIMESTAMP,
    revoked_reason      VARCHAR2(100),
    CONSTRAINT fk_session_user FOREIGN KEY (user_id) REFERENCES app_users(user_id)
);

CREATE INDEX idx_sessions_user ON user_sessions (user_id);
CREATE INDEX idx_sessions_expiry ON user_sessions (absolute_expires_at);

CREATE TABLE auth_login_attempts (
    attempt_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username_hash VARCHAR2(64) NOT NULL,
    ip_address    VARCHAR2(64) NOT NULL,
    success       NUMBER(1) NOT NULL,
    attempted_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_login_attempt_success CHECK (success IN (0,1))
);

CREATE INDEX idx_login_attempt_user_time ON auth_login_attempts (username_hash, attempted_at);
CREATE INDEX idx_login_attempt_ip_time ON auth_login_attempts (ip_address, attempted_at);

CREATE TABLE password_reset_tokens (
    token_hash   VARCHAR2(64) PRIMARY KEY,
    user_id      NUMBER NOT NULL,
    created_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    expires_at   TIMESTAMP NOT NULL,
    used_at      TIMESTAMP,
    requested_ip VARCHAR2(64),
    CONSTRAINT fk_reset_user FOREIGN KEY (user_id) REFERENCES app_users(user_id)
);

CREATE INDEX idx_reset_user ON password_reset_tokens (user_id);

CREATE TABLE auth_roles (
    role_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code    VARCHAR2(60) NOT NULL,
    role_name    VARCHAR2(100) NOT NULL,
    description  VARCHAR2(500),
    is_system    NUMBER(1) DEFAULT 1 NOT NULL,
    is_active    NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT uq_auth_role_code UNIQUE (role_code),
    CONSTRAINT ck_auth_role_system CHECK (is_system IN (0,1)),
    CONSTRAINT ck_auth_role_active CHECK (is_active IN (0,1))
);

CREATE TABLE auth_permissions (
    permission_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission_code VARCHAR2(80) NOT NULL,
    description     VARCHAR2(500),
    is_active       NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT uq_auth_permission_code UNIQUE (permission_code),
    CONSTRAINT ck_auth_permission_active CHECK (is_active IN (0,1))
);

CREATE TABLE auth_role_permissions (
    role_id       NUMBER NOT NULL,
    permission_id NUMBER NOT NULL,
    CONSTRAINT pk_auth_role_permissions PRIMARY KEY (role_id, permission_id),
    CONSTRAINT fk_auth_rp_role FOREIGN KEY (role_id) REFERENCES auth_roles(role_id),
    CONSTRAINT fk_auth_rp_permission FOREIGN KEY (permission_id) REFERENCES auth_permissions(permission_id)
);

CREATE TABLE auth_user_roles (
    user_id     NUMBER NOT NULL,
    role_id     NUMBER NOT NULL,
    assigned_by NUMBER,
    assigned_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    expires_at  TIMESTAMP,
    CONSTRAINT pk_auth_user_roles PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_auth_ur_user FOREIGN KEY (user_id) REFERENCES app_users(user_id),
    CONSTRAINT fk_auth_ur_role FOREIGN KEY (role_id) REFERENCES auth_roles(role_id),
    CONSTRAINT fk_auth_ur_assigner FOREIGN KEY (assigned_by) REFERENCES app_users(user_id)
);

CREATE INDEX idx_auth_user_roles_role ON auth_user_roles (role_id);

-- ------------------------------------------------------------
-- PAYROLL (one row per employee per pay period, from Excel upload)
-- ------------------------------------------------------------
CREATE TABLE payroll (
    payroll_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id          NUMBER NOT NULL,
    employee_code         VARCHAR2(20) NOT NULL,
    pay_month             NUMBER(2) NOT NULL,
    pay_year              NUMBER(4) NOT NULL,
    working_days          NUMBER(5,2) DEFAULT 0,
    present_days          NUMBER(5,2) DEFAULT 0,
    absent_days           NUMBER(5,2) DEFAULT 0,
    paid_leave_days       NUMBER(5,2) DEFAULT 0,
    lop_days               NUMBER(5,2) DEFAULT 0,
    half_days              NUMBER(5,2) DEFAULT 0,
    late_marks              NUMBER(5,2) DEFAULT 0,
    ot_hours                 NUMBER(6,2) DEFAULT 0,
    basic_salary            NUMBER(12,2) DEFAULT 0,
    hra                       NUMBER(12,2) DEFAULT 0,
    da                        NUMBER(12,2) DEFAULT 0,
    conveyance                NUMBER(12,2) DEFAULT 0,
    medical_allowance         NUMBER(12,2) DEFAULT 0,
    special_allowance         NUMBER(12,2) DEFAULT 0,
    bonus                     NUMBER(12,2) DEFAULT 0,
    other_earnings            NUMBER(12,2) DEFAULT 0,
    total_earnings            NUMBER(12,2) DEFAULT 0,
    provident_fund            NUMBER(12,2) DEFAULT 0,
    professional_tax          NUMBER(12,2) DEFAULT 0,
    income_tax                NUMBER(12,2) DEFAULT 0,
    other_deductions          NUMBER(12,2) DEFAULT 0,
    total_deductions          NUMBER(12,2) DEFAULT 0,
    net_salary                NUMBER(12,2) DEFAULT 0,
    -- Extended columns to support company salary sheets that use a richer
    -- set of earning/deduction line items (see sql/03_alter_payroll_flex_columns.sql
    -- for the idempotent migration if this table already exists in your DB).
    professional_development NUMBER(12,2) DEFAULT 0,
    other_allowance           NUMBER(12,2) DEFAULT 0,
    food_allowance             NUMBER(12,2) DEFAULT 0,
    employer_contribution     NUMBER(12,2) DEFAULT 0,
    lop_amount                 NUMBER(12,2) DEFAULT 0,
    esi                         NUMBER(12,2) DEFAULT 0,
    gross_salary                NUMBER(12,2) DEFAULT 0,
    remarks                     VARCHAR2(500),
    source_file                VARCHAR2(300),
    uploaded_at                TIMESTAMP DEFAULT SYSTIMESTAMP,
    -- Payslip email tracking (see sql/05_alter_payroll_email_status.sql for
    -- the idempotent migration if this table already exists in your DB).
    email_status                VARCHAR2(20),
    email_sent_at               TIMESTAMP,
    email_error                 VARCHAR2(500),
    CONSTRAINT fk_payroll_employee FOREIGN KEY (employee_id) REFERENCES employees(employee_id),
    CONSTRAINT uq_payroll_emp_period UNIQUE (employee_id, pay_month, pay_year)
);

CREATE INDEX idx_payroll_period ON payroll (pay_year, pay_month);
CREATE INDEX idx_payroll_empcode ON payroll (employee_code);

-- ------------------------------------------------------------
-- UPLOAD_BATCHES (audit trail of each Excel upload)
-- ------------------------------------------------------------
CREATE TABLE upload_batches (
    batch_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_name       VARCHAR2(300),
    pay_month       NUMBER(2),
    pay_year        NUMBER(4),
    total_rows      NUMBER(6) DEFAULT 0,
    matched_rows    NUMBER(6) DEFAULT 0,
    unmatched_rows  NUMBER(6) DEFAULT 0,
    unmatched_codes CLOB,
    uploaded_by     VARCHAR2(60),
    uploaded_at     TIMESTAMP DEFAULT SYSTIMESTAMP
);

COMMIT;
