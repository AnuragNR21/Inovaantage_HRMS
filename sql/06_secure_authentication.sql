-- Additive, idempotent migration for database-backed authentication.
DECLARE
  PROCEDURE add_col(p_table VARCHAR2, p_name VARCHAR2, p_ddl VARCHAR2) IS
    v_count NUMBER;
  BEGIN
    SELECT COUNT(*) INTO v_count FROM user_tab_columns
     WHERE table_name = UPPER(p_table) AND column_name = UPPER(p_name);
    IF v_count = 0 THEN
      EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' ADD (' || p_ddl || ')';
    END IF;
  END;
BEGIN
  add_col('APP_USERS', 'EMAIL', 'email VARCHAR2(150)');
  add_col('APP_USERS', 'FAILED_LOGIN_COUNT', 'failed_login_count NUMBER(5) DEFAULT 0 NOT NULL');
  add_col('APP_USERS', 'LAST_FAILED_LOGIN_AT', 'last_failed_login_at TIMESTAMP');
  add_col('APP_USERS', 'LOCKED_UNTIL', 'locked_until TIMESTAMP');
  add_col('APP_USERS', 'LAST_LOGIN_AT', 'last_login_at TIMESTAMP');
  add_col('APP_USERS', 'PASSWORD_CHANGED_AT', 'password_changed_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL');
  add_col('APP_USERS', 'PASSWORD_VERSION', 'password_version NUMBER(10) DEFAULT 1 NOT NULL');
  add_col('APP_USERS', 'MUST_CHANGE_PASSWORD', 'must_change_password NUMBER(1) DEFAULT 1 NOT NULL');
END;
/

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'USER_SESSIONS';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE user_sessions (
        token_hash VARCHAR2(64) PRIMARY KEY, user_id NUMBER NOT NULL,
        created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        last_seen_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        expires_at TIMESTAMP NOT NULL, absolute_expires_at TIMESTAMP NOT NULL,
        ip_address VARCHAR2(64), user_agent VARCHAR2(500), password_version NUMBER(10) NOT NULL,
        revoked_at TIMESTAMP, revoked_reason VARCHAR2(100),
        CONSTRAINT fk_session_user FOREIGN KEY (user_id) REFERENCES app_users(user_id))]';
    EXECUTE IMMEDIATE 'CREATE INDEX idx_sessions_user ON user_sessions (user_id)';
    EXECUTE IMMEDIATE 'CREATE INDEX idx_sessions_expiry ON user_sessions (absolute_expires_at)';
  END IF;

  SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'AUTH_LOGIN_ATTEMPTS';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE auth_login_attempts (
        attempt_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username_hash VARCHAR2(64) NOT NULL, ip_address VARCHAR2(64) NOT NULL,
        success NUMBER(1) NOT NULL, attempted_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
        CONSTRAINT ck_login_attempt_success CHECK (success IN (0,1)))]';
    EXECUTE IMMEDIATE 'CREATE INDEX idx_login_attempt_user_time ON auth_login_attempts (username_hash, attempted_at)';
    EXECUTE IMMEDIATE 'CREATE INDEX idx_login_attempt_ip_time ON auth_login_attempts (ip_address, attempted_at)';
  END IF;

  SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'PASSWORD_RESET_TOKENS';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE TABLE password_reset_tokens (
        token_hash VARCHAR2(64) PRIMARY KEY, user_id NUMBER NOT NULL,
        created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, expires_at TIMESTAMP NOT NULL,
        used_at TIMESTAMP, requested_ip VARCHAR2(64),
        CONSTRAINT fk_reset_user FOREIGN KEY (user_id) REFERENCES app_users(user_id))]';
    EXECUTE IMMEDIATE 'CREATE INDEX idx_reset_user ON password_reset_tokens (user_id)';
  END IF;
END;
/

COMMIT;
