-- Additive, idempotent migration for enterprise RBAC.
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'AUTH_ROLES';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[CREATE TABLE auth_roles (
      role_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      role_code VARCHAR2(60) NOT NULL, role_name VARCHAR2(100) NOT NULL,
      description VARCHAR2(500), is_system NUMBER(1) DEFAULT 1 NOT NULL,
      is_active NUMBER(1) DEFAULT 1 NOT NULL,
      CONSTRAINT uq_auth_role_code UNIQUE (role_code),
      CONSTRAINT ck_auth_role_system CHECK (is_system IN (0,1)),
      CONSTRAINT ck_auth_role_active CHECK (is_active IN (0,1)))]';
  END IF;

  SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'AUTH_PERMISSIONS';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[CREATE TABLE auth_permissions (
      permission_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      permission_code VARCHAR2(80) NOT NULL, description VARCHAR2(500),
      is_active NUMBER(1) DEFAULT 1 NOT NULL,
      CONSTRAINT uq_auth_permission_code UNIQUE (permission_code),
      CONSTRAINT ck_auth_permission_active CHECK (is_active IN (0,1)))]';
  END IF;

  SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'AUTH_ROLE_PERMISSIONS';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[CREATE TABLE auth_role_permissions (
      role_id NUMBER NOT NULL, permission_id NUMBER NOT NULL,
      CONSTRAINT pk_auth_role_permissions PRIMARY KEY (role_id, permission_id),
      CONSTRAINT fk_auth_rp_role FOREIGN KEY (role_id) REFERENCES auth_roles(role_id),
      CONSTRAINT fk_auth_rp_permission FOREIGN KEY (permission_id) REFERENCES auth_permissions(permission_id))]';
  END IF;

  SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'AUTH_USER_ROLES';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[CREATE TABLE auth_user_roles (
      user_id NUMBER NOT NULL, role_id NUMBER NOT NULL, assigned_by NUMBER,
      assigned_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, expires_at TIMESTAMP,
      CONSTRAINT pk_auth_user_roles PRIMARY KEY (user_id, role_id),
      CONSTRAINT fk_auth_ur_user FOREIGN KEY (user_id) REFERENCES app_users(user_id),
      CONSTRAINT fk_auth_ur_role FOREIGN KEY (role_id) REFERENCES auth_roles(role_id),
      CONSTRAINT fk_auth_ur_assigner FOREIGN KEY (assigned_by) REFERENCES app_users(user_id))]';
    EXECUTE IMMEDIATE 'CREATE INDEX idx_auth_user_roles_role ON auth_user_roles (role_id)';
  END IF;
END;
