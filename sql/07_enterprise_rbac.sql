DECLARE
  PROCEDURE assign_legacy(p_legacy_role VARCHAR2, p_role_code VARCHAR2) IS
  BEGIN
    INSERT INTO auth_user_roles (user_id, role_id, assigned_by)
    SELECT u.user_id, r.role_id, NULL FROM app_users u CROSS JOIN auth_roles r
     WHERE u.role = p_legacy_role AND r.role_code = p_role_code
       AND NOT EXISTS (SELECT 1 FROM auth_user_roles ur
                        WHERE ur.user_id = u.user_id AND ur.role_id = r.role_id);
  END;
BEGIN
  assign_legacy('ADMIN', 'SYSTEM_ADMIN');
  assign_legacy('ADMIN', 'HR_ADMIN');
  assign_legacy('ADMIN', 'PAYROLL_OPERATOR');
  assign_legacy('ADMIN', 'PAYROLL_APPROVER');
  assign_legacy('HR', 'HR_ADMIN');
  assign_legacy('HR', 'PAYROLL_OPERATOR');
  assign_legacy('VIEWER', 'AUDITOR');
END;
