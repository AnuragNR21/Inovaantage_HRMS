-- Additive, idempotent payroll-run lifecycle migration.
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'PAYROLL_RUNS';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[CREATE TABLE payroll_runs (
      run_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      pay_month NUMBER(2) NOT NULL,
      pay_year NUMBER(4) NOT NULL,
      status VARCHAR2(20) DEFAULT 'DRAFT' NOT NULL,
      source_file VARCHAR2(300),
      total_rows NUMBER(8) DEFAULT 0 NOT NULL,
      validated_rows NUMBER(8) DEFAULT 0 NOT NULL,
      error_message VARCHAR2(500),
      created_by NUMBER,
      approved_by NUMBER,
      finalized_by NUMBER,
      approved_at TIMESTAMP,
      finalized_at TIMESTAMP,
      created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      version_no NUMBER(10) DEFAULT 1 NOT NULL,
      CONSTRAINT uq_payroll_run_period UNIQUE (pay_month, pay_year),
      CONSTRAINT ck_payroll_run_month CHECK (pay_month BETWEEN 1 AND 12),
      CONSTRAINT ck_payroll_run_year CHECK (pay_year BETWEEN 2000 AND 2100),
      CONSTRAINT ck_payroll_run_status CHECK (status IN ('DRAFT','PROCESSING','VALIDATED','APPROVED','FINALIZED','HOLD','FAILED')),
      CONSTRAINT fk_payroll_run_creator FOREIGN KEY (created_by) REFERENCES app_users(user_id),
      CONSTRAINT fk_payroll_run_approver FOREIGN KEY (approved_by) REFERENCES app_users(user_id),
      CONSTRAINT fk_payroll_run_finalizer FOREIGN KEY (finalized_by) REFERENCES app_users(user_id))]';
    EXECUTE IMMEDIATE 'CREATE INDEX idx_payroll_runs_status ON payroll_runs (status)';
  END IF;

  SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'PAYROLL_RUN_EVENTS';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[CREATE TABLE payroll_run_events (
      event_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      run_id NUMBER NOT NULL,
      event_type VARCHAR2(60) NOT NULL,
      from_state VARCHAR2(20),
      to_state VARCHAR2(20),
      actor_user_id NUMBER,
      details VARCHAR2(4000),
      created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT fk_payroll_event_run FOREIGN KEY (run_id) REFERENCES payroll_runs(run_id),
      CONSTRAINT fk_payroll_event_actor FOREIGN KEY (actor_user_id) REFERENCES app_users(user_id))]';
    EXECUTE IMMEDIATE 'CREATE INDEX idx_payroll_events_run ON payroll_run_events (run_id, created_at)';
  END IF;

  SELECT COUNT(*) INTO v_count FROM user_tab_columns
   WHERE table_name = 'PAYROLL' AND column_name = 'RUN_ID';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE payroll ADD (run_id NUMBER)';
  END IF;

  SELECT COUNT(*) INTO v_count FROM user_tab_columns
   WHERE table_name = 'UPLOAD_BATCHES' AND column_name = 'RUN_ID';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE upload_batches ADD (run_id NUMBER)';
  END IF;
END;
/

MERGE INTO payroll_runs r
USING (
  SELECT pay_month, pay_year, MIN(source_file) source_file,
         COUNT(*) total_rows, MIN(uploaded_at) created_at
    FROM payroll
   GROUP BY pay_month, pay_year
) p
ON (r.pay_month = p.pay_month AND r.pay_year = p.pay_year)
WHEN NOT MATCHED THEN INSERT
  (pay_month, pay_year, status, source_file, total_rows, validated_rows,
   created_at, updated_at)
VALUES
  (p.pay_month, p.pay_year, 'FINALIZED', p.source_file, p.total_rows,
   p.total_rows, p.created_at, p.created_at);

UPDATE payroll p
   SET run_id = (SELECT r.run_id FROM payroll_runs r
                  WHERE r.pay_month = p.pay_month AND r.pay_year = p.pay_year)
 WHERE run_id IS NULL;

UPDATE upload_batches b
   SET run_id = (SELECT r.run_id FROM payroll_runs r
                  WHERE r.pay_month = b.pay_month AND r.pay_year = b.pay_year)
 WHERE run_id IS NULL
   AND EXISTS (SELECT 1 FROM payroll_runs r
                WHERE r.pay_month = b.pay_month AND r.pay_year = b.pay_year);

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM user_constraints WHERE constraint_name = 'FK_PAYROLL_RUN';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE payroll ADD CONSTRAINT fk_payroll_run FOREIGN KEY (run_id) REFERENCES payroll_runs(run_id)';
  END IF;

  SELECT COUNT(*) INTO v_count FROM user_constraints WHERE constraint_name = 'FK_UPLOAD_BATCH_RUN';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE upload_batches ADD CONSTRAINT fk_upload_batch_run FOREIGN KEY (run_id) REFERENCES payroll_runs(run_id)';
  END IF;

  SELECT COUNT(*) INTO v_count FROM user_tab_columns
   WHERE table_name = 'PAYROLL' AND column_name = 'RUN_ID' AND nullable = 'Y';
  IF v_count = 1 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE payroll MODIFY (run_id NOT NULL)';
  END IF;
END;
/

INSERT INTO payroll_run_events (run_id, event_type, from_state, to_state, details)
SELECT r.run_id, 'PAYROLL_MIGRATED', NULL, 'FINALIZED', 'Historical payroll migrated as finalized.'
  FROM payroll_runs r
 WHERE r.status = 'FINALIZED'
   AND NOT EXISTS (SELECT 1 FROM payroll_run_events e WHERE e.run_id = r.run_id);

COMMIT;
