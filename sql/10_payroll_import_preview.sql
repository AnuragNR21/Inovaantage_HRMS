-- Durable, user-bound salary import previews and idempotent confirmation links.
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'PAYROLL_IMPORTS';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[CREATE TABLE payroll_imports (
      import_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      preview_token_hash VARCHAR2(64) NOT NULL,
      created_by NUMBER NOT NULL,
      pay_month NUMBER(2) NOT NULL,
      pay_year NUMBER(4) NOT NULL,
      source_file VARCHAR2(200) NOT NULL,
      file_size NUMBER(12) NOT NULL,
      file_sha256 VARCHAR2(64) NOT NULL,
      mime_type VARCHAR2(150) NOT NULL,
      status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
      rows_payload CLOB NOT NULL,
      summary_payload CLOB NOT NULL,
      require_all_employees NUMBER(1) DEFAULT 1 NOT NULL,
      expires_at TIMESTAMP NOT NULL,
      run_id NUMBER,
      error_message VARCHAR2(500),
      confirmed_at TIMESTAMP,
      created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT uq_payroll_import_token UNIQUE (preview_token_hash),
      CONSTRAINT ck_payroll_import_month CHECK (pay_month BETWEEN 1 AND 12),
      CONSTRAINT ck_payroll_import_year CHECK (pay_year BETWEEN 2000 AND 2100),
      CONSTRAINT ck_payroll_import_status CHECK (status IN ('PENDING','FAILED','IMPORTED','EXPIRED')),
      CONSTRAINT ck_payroll_import_all_emp CHECK (require_all_employees IN (0,1)),
      CONSTRAINT fk_payroll_import_user FOREIGN KEY (created_by) REFERENCES app_users(user_id),
      CONSTRAINT fk_payroll_import_run FOREIGN KEY (run_id) REFERENCES payroll_runs(run_id))]';
    EXECUTE IMMEDIATE 'CREATE INDEX idx_payroll_import_expiry ON payroll_imports (status, expires_at)';
    EXECUTE IMMEDIATE 'CREATE INDEX idx_payroll_import_user ON payroll_imports (created_by, created_at)';
  END IF;

  SELECT COUNT(*) INTO v_count FROM user_tab_columns
   WHERE table_name = 'PAYROLL_RUNS' AND column_name = 'IMPORT_ID';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE payroll_runs ADD (import_id NUMBER)';
  END IF;

  SELECT COUNT(*) INTO v_count FROM user_constraints
   WHERE constraint_name = 'FK_PAYROLL_RUN_IMPORT';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE payroll_runs ADD CONSTRAINT fk_payroll_run_import FOREIGN KEY (import_id) REFERENCES payroll_imports(import_id)';
  END IF;

  SELECT COUNT(*) INTO v_count FROM user_constraints
   WHERE constraint_name = 'UQ_PAYROLL_RUN_IMPORT';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE payroll_runs ADD CONSTRAINT uq_payroll_run_import UNIQUE (import_id)';
  END IF;
END;
/

COMMIT;
