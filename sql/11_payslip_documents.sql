-- Secure, one-to-one payslip artifacts generated from finalized payroll rows.
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'PAYSLIP_DOCUMENTS';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[CREATE TABLE payslip_documents (
      document_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      payroll_id NUMBER NOT NULL,
      run_id NUMBER NOT NULL,
      employee_id NUMBER NOT NULL,
      status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
      content BLOB,
      sha256 VARCHAR2(64),
      file_size NUMBER(12),
      attempt_count NUMBER(8) DEFAULT 0 NOT NULL,
      generation_token VARCHAR2(64),
      lease_until TIMESTAMP,
      generated_at TIMESTAMP,
      error_message VARCHAR2(500),
      created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT uq_payslip_payroll UNIQUE (payroll_id),
      CONSTRAINT ck_payslip_status CHECK (status IN ('PENDING','GENERATED','FAILED')),
      CONSTRAINT ck_payslip_attempts CHECK (attempt_count >= 0),
      CONSTRAINT fk_payslip_payroll FOREIGN KEY (payroll_id) REFERENCES payroll(payroll_id),
      CONSTRAINT fk_payslip_run FOREIGN KEY (run_id) REFERENCES payroll_runs(run_id),
      CONSTRAINT fk_payslip_employee FOREIGN KEY (employee_id) REFERENCES employees(employee_id))]';
    EXECUTE IMMEDIATE 'CREATE INDEX idx_payslip_run_status ON payslip_documents (run_id, status)';
    EXECUTE IMMEDIATE 'CREATE INDEX idx_payslip_employee ON payslip_documents (employee_id, status)';
  END IF;
END;
/

COMMIT;
