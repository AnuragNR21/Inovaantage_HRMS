-- Idempotent queue for one asynchronous delivery job per generated payslip.
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'PAYSLIP_EMAIL_JOBS';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[CREATE TABLE payslip_email_jobs (
      job_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      document_id NUMBER NOT NULL,
      payroll_id NUMBER NOT NULL,
      run_id NUMBER NOT NULL,
      employee_id NUMBER NOT NULL,
      email_address VARCHAR2(254),
      status VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
      attempt_count NUMBER(8) DEFAULT 0 NOT NULL,
      max_attempts NUMBER(8) DEFAULT 5 NOT NULL,
      processing_token VARCHAR2(64),
      lease_until TIMESTAMP,
      next_attempt_at TIMESTAMP,
      last_attempt_at TIMESTAMP,
      sent_at TIMESTAMP,
      failure_reason VARCHAR2(500),
      idempotency_key VARCHAR2(64) NOT NULL,
      worker_id VARCHAR2(100),
      created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      updated_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT uq_email_job_document UNIQUE (document_id),
      CONSTRAINT uq_email_job_idempotency UNIQUE (idempotency_key),
      CONSTRAINT ck_email_job_status CHECK (status IN ('PENDING','PROCESSING','SENT','FAILED')),
      CONSTRAINT ck_email_job_attempts CHECK (attempt_count >= 0 AND max_attempts >= 0),
      CONSTRAINT fk_email_job_document FOREIGN KEY (document_id) REFERENCES payslip_documents(document_id),
      CONSTRAINT fk_email_job_payroll FOREIGN KEY (payroll_id) REFERENCES payroll(payroll_id),
      CONSTRAINT fk_email_job_run FOREIGN KEY (run_id) REFERENCES payroll_runs(run_id),
      CONSTRAINT fk_email_job_employee FOREIGN KEY (employee_id) REFERENCES employees(employee_id))]';
    EXECUTE IMMEDIATE 'CREATE INDEX idx_email_job_queue ON payslip_email_jobs (status, next_attempt_at, lease_until)';
    EXECUTE IMMEDIATE 'CREATE INDEX idx_email_job_run ON payslip_email_jobs (run_id, status)';
  END IF;
END;
/

COMMIT;
