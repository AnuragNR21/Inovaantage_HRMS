-- Append-only audit trail for security and payroll-sensitive actions.
DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'AUDIT_LOGS';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[CREATE TABLE audit_logs (
      audit_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      actor_user_id NUMBER,
      action VARCHAR2(80) NOT NULL,
      resource_type VARCHAR2(60) NOT NULL,
      resource_id VARCHAR2(120),
      result VARCHAR2(20) DEFAULT 'SUCCESS' NOT NULL,
      ip_address VARCHAR2(64),
      user_agent VARCHAR2(500),
      metadata VARCHAR2(4000),
      created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT ck_audit_result CHECK (result IN ('SUCCESS','FAILURE','DENIED')))]';
    EXECUTE IMMEDIATE 'CREATE INDEX idx_audit_created ON audit_logs (created_at, audit_id)';
    EXECUTE IMMEDIATE 'CREATE INDEX idx_audit_action ON audit_logs (action, created_at)';
    EXECUTE IMMEDIATE 'CREATE INDEX idx_audit_actor ON audit_logs (actor_user_id, created_at)';
  END IF;
END;
/

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM user_constraints WHERE constraint_name = 'FK_AUDIT_ACTOR';
  IF v_count = 1 THEN EXECUTE IMMEDIATE 'ALTER TABLE audit_logs DROP CONSTRAINT fk_audit_actor'; END IF;
END;
/

DECLARE
  v_count NUMBER;
BEGIN
  SELECT COUNT(*) INTO v_count FROM user_triggers WHERE trigger_name = 'TRG_AUDIT_LOGS_IMMUTABLE';
  IF v_count = 0 THEN
    EXECUTE IMMEDIATE q'[
      CREATE OR REPLACE TRIGGER trg_audit_logs_immutable
      BEFORE UPDATE OR DELETE ON audit_logs
      BEGIN
        RAISE_APPLICATION_ERROR(-20081, 'Audit records are append-only.');
      END;]';
  END IF;
END;
/

COMMIT;
